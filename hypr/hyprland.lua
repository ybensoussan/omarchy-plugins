-- Load the active display profile (generated by omarchy-display-profiles). The bar reads this same file.
do
  local config_dir = os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")
  local active_profile = config_dir .. "/hypr/workspace-profile.lua"
  local file = io.open(active_profile, "r")
  if file then
    file:close()
  dofile(active_profile)
  end
end

